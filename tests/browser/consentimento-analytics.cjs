(async () => {
  const { chromium } = await import(process.env.CONSENTIMENTO_PLAYWRIGHT || "playwright");
  const assert = (await import("node:assert/strict")).default;
  const fs = await import("node:fs/promises");
  const path = await import("node:path");
  const base = process.env.CONSENTIMENTO_TEST_URL || "http://127.0.0.1:3109";
  const evidencias = path.resolve(".impeccable/review");
  await fs.mkdir(evidencias, { recursive: true });
  const browser = await chromium.launch({ executablePath: "/usr/bin/chromium", args: ["--no-sandbox"] });
  const contexto = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const externas = [];
  await contexto.route("**/*", async rota => {
    const url = new URL(rota.request().url());
    if (url.origin !== new URL(base).origin) {
      externas.push({ url: url.href, referrer: rota.request().headers().referer || "" });
      await rota.abort();
    } else await rota.continue();
  });
  const pagina = await contexto.newPage();
  const quadro = () => pagina.frames().find(frame => frame.url().endsWith("/api/analytics"));
  const eventos = async () => quadro()?.evaluate(() => (window.dataLayer || []).map(item => Array.from(item))) || [];
  const loaders = () => externas.filter(item => { const u = new URL(item.url); return u.hostname === "www.googletagmanager.com" && u.pathname === "/gtag/js"; }).length;
  const esperar = () => pagina.waitForTimeout(1200);
  const publico = `${base}/sobre?q=busca-sintetica%40example.invalid#fragmento-sintetico`;
  const cookie = nome => contexto.cookies().then(cookies => cookies.find(item => item.name === nome));

  const respostaInicial = await pagina.goto(publico);
  assert.ok(!respostaInicial.headers()["content-security-policy"].includes("google"), "página principal não autoriza conexões Google");
  await pagina.getByRole("button", { name: "Recusar medição", exact: true }).waitFor();
  await esperar();
  assert.equal(loaders(), 0, "estado inicial não carrega Google");
  assert.equal(await cookie("ndb_eventos"), undefined);
  await contexto.addCookies([{ name: "ndb_sessao", value: "sessao-sintetica-sem-pessoa-real", url: base }, { name: "ndb_google", value: "oauth-sintetico", url: base }]);
  await pagina.evaluate(() => { localStorage.setItem("ndb:tema", "escuro"); localStorage.setItem("ndb:cadastro", "rascunho-sintetico"); });
  const recusar = pagina.getByRole("button", { name: "Recusar medição", exact: true });
  const aceitar = pagina.getByRole("button", { name: "Aceitar medição", exact: true });
  assert.equal(await recusar.getAttribute("class"), await aceitar.getAttribute("class"), "ações com destaque igual");
  if (process.env.CONSENTIMENTO_CAPTURAR === "1") await pagina.screenshot({ path: path.join(evidencias, "desktop.png"), fullPage: true });
  await pagina.setViewportSize({ width: 390, height: 844 });
  if (process.env.CONSENTIMENTO_CAPTURAR === "1") await pagina.screenshot({ path: path.join(evidencias, "mobile.png"), fullPage: true });
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "sem transbordamento horizontal");
  await recusar.click();
  await esperar();
  assert.equal(loaders(), 0, "recusa não carrega Google");
  await pagina.reload();
  await esperar();
  assert.equal(loaders(), 0, "nova visita recusada não carrega Google");
  await pagina.getByRole("button", { name: "Preferências de privacidade", exact: true }).click();
  await pagina.evaluate(() => { document.cookie = 'ndb_eventos=%5B%7B%22nome%22%3A%22login%22%7D%5D; Path=/'; });
  await pagina.evaluate(() => {
    window.__ndbProntoRecebido = false;
    addEventListener("message", evento => {
      const frame = document.querySelector('iframe[title="Medição opcional"]');
      if (evento.origin === "null" && evento.source === frame?.contentWindow && evento.data?.tipo === "ndb:pronto") window.__ndbProntoRecebido = true;
    });
  });
  await pagina.getByRole("button", { name: "Aceitar medição", exact: true }).click();
  await pagina.waitForFunction(() => window.__ndbProntoRecebido === true);
  await esperar();
  assert.ok(loaders() > 0, "aceitação permite somente o carregador interceptado");
  assert.ok(externas.filter(item => new URL(item.url).hostname === "www.googletagmanager.com").every(item => !item.referrer), "carregador sem referrer");
  const primeiraPagina = (await eventos()).find(item => item[0] === "event" && item[1] === "page_view");
  assert.ok(primeiraPagina, "page_view explícito");
  assert.equal(primeiraPagina[2].page_location, `${base}/sobre`);
  assert.equal(primeiraPagina[2].page_title, "Como funciona");
  assert.equal(primeiraPagina[2].page_referrer, "");
  assert.equal(await cookie("ndb_eventos"), undefined, "não envia fila anterior à aceitação");
  await pagina.evaluate(() => {
    const alvo = document.createElement("button");
    alvo.dataset.medir = "contato_negocio"; alvo.dataset.canal = "site"; alvo.dataset.uf = "BA";
    alvo.dataset.email = "sintetico@example.invalid"; alvo.dataset.categoria = "Saúde";
    document.body.append(alvo); alvo.click(); alvo.remove();
  });
  await esperar();
  const contato = (await eventos()).find(item => item[1] === "contato_negocio");
  assert.ok(contato);
  assert.deepEqual(Object.keys(contato[2]).sort(), ["canal", "uf", "page_location", "page_title", "page_referrer"].sort());
  assert.ok(!JSON.stringify(await eventos()).includes("busca-sintetica"));
  assert.ok(!JSON.stringify(await eventos()).includes("sintetico@example.invalid"));
  assert.ok(!JSON.stringify(await eventos()).includes("fragmento-sintetico"));

  const escolhaAntes = (await cookie("ndb_consentimento")).value;
  await pagina.evaluate(() => { window.__ndbReaceitacao = "sem-navegacao"; });
  await pagina.getByRole("button", { name: "Preferências de privacidade", exact: true }).click();
  await pagina.getByRole("button", { name: "Aceitar medição", exact: true }).click();
  await esperar();
  assert.notEqual((await cookie("ndb_consentimento")).value, escolhaAntes, "reaceitação grava uma escolha nova");
  await pagina.evaluate(() => {
    const alvo = document.createElement("button");
    alvo.dataset.medir = "contato_negocio"; alvo.dataset.canal = "telefone"; alvo.dataset.uf = "BA";
    document.body.append(alvo); alvo.click(); alvo.remove();
  });
  await esperar();
  assert.equal(await pagina.evaluate(() => window.__ndbReaceitacao), "sem-navegacao", "reaceitação não navega nem recarrega o documento principal");
  assert.ok((await eventos()).some(item => item[0] === "event" && item[1] === "contato_negocio" && item[2].canal === "telefone"), "reaceitação na mesma rota mantém o envio de uma interação permitida");

  await pagina.evaluate(() => { window.__documentoConsentimento = "mesmo-documento"; });
  await pagina.getByRole("link", { name: "Cadastrar", exact: true }).click();
  await pagina.waitForURL("**/participar");
  await esperar();
  assert.equal(await pagina.evaluate(() => window.__documentoConsentimento), "mesmo-documento", "navegação cliente real");
  await pagina.getByRole("link", { name: "Entrar", exact: true }).first().click();
  await pagina.waitForURL("**/entrar*");
  await esperar();
  assert.equal(await pagina.locator('iframe[title="Medição opcional"]').count(), 0, "área privada não mantém carregador");
  const privado = loaders();
  await esperar();
  assert.equal(loaders(), privado);
  await pagina.goto(`${base}/sobre`);
  await esperar();
  assert.ok(quadro(), "nova visita aceita carrega medição");
  await pagina.evaluate(() => { document.cookie = '_ga=identificador-sintetico; Path=/'; document.cookie = 'ndb_eventos=fila-sintetica; Path=/'; });
  await pagina.getByRole("button", { name: "Preferências de privacidade", exact: true }).click();
  await pagina.getByRole("button", { name: "Recusar medição", exact: true }).click();
  await esperar();
  assert.equal(await pagina.locator('iframe[title="Medição opcional"]').count(), 0);
  assert.equal(await cookie("_ga"), undefined);
  assert.equal(await cookie("ndb_eventos"), undefined);
  assert.equal((await cookie("ndb_sessao")).value, "sessao-sintetica-sem-pessoa-real");
  assert.equal((await cookie("ndb_google")).value, "oauth-sintetico");
  assert.equal(await pagina.evaluate(() => localStorage.getItem("ndb:cadastro")), "rascunho-sintetico");
  assert.equal(await pagina.evaluate(() => localStorage.getItem("ndb:tema")), "escuro");
  const revogado = loaders();
  await pagina.reload();
  await esperar();
  assert.equal(loaders(), revogado, "revogação persiste na nova visita");

  const falha = await browser.newContext();
  await falha.route("**/*", rota => new URL(rota.request().url()).origin === new URL(base).origin ? rota.continue() : rota.abort());
  await falha.addInitScript(() => Object.defineProperty(document, "cookie", { configurable: true, get() { return ""; }, set() {} }));
  const paginaFalha = await falha.newPage();
  await paginaFalha.goto(`${base}/sobre`);
  await paginaFalha.getByRole("button", { name: "Aceitar medição", exact: true }).click();
  await paginaFalha.getByRole("alert").filter({ hasText: "Não foi possível guardar sua escolha" }).waitFor();
  assert.equal(await paginaFalha.locator('iframe[title="Medição opcional"]').count(), 0, "falha de armazenamento não autoriza");

  console.log(JSON.stringify({ resultado: "PASS", casos: ["inicial", "recusa", "nova visita recusada", "aceitação", "fila antiga descartada", "listas de parâmetros", "reaceitação na mesma rota", "navegação cliente privada", "nova visita aceita", "revogação", "nova visita revogada", "armazenamento bloqueado", "cookies funcionais e rascunho preservados", "desktop e celular"], tentativasExternasInterceptadas: externas, limite: "O script Google foi abortado. As asserções verificam a aplicação e sua dataLayer, não o recebimento na propriedade Google nem login real." }, null, 2));
  await browser.close();
})().catch(erro => { console.error(erro); process.exit(1); });
